def require(value, reason):
    if not value:
        raise ValueError(reason)


def _path(payload, at, basename):
    """One fixed-width lexical match; never searches elsewhere in the payload."""
    end = at + len(PATH_PREFIX) + 33 + len(basename)
    if end > len(payload) or payload[at:at + len(PATH_PREFIX)] != PATH_PREFIX:
        return None
    key_at = at + len(PATH_PREFIX)
    key = payload[key_at:key_at + 32]
    if (not all(48 <= c <= 57 or 97 <= c <= 102 for c in key) or
            payload[key_at + 32:end] != b"/" + basename):
        return None
    return payload[at:end], end


def decode(payload):
    """Consume every print fragment, with at most16 archive-newline masks.

    Fragments may interleave between print calls. Their per-stream order stays
    exact. A single bounded final-record split is independent of physical lines.
    """
    require(type(payload) is bytes and 0 < len(payload) <= 1048576, "link dump byte budget")
    require(all(c == 10 or 32 <= c <= 126 for c in payload), "link dump ASCII output framing")
    archives, indexes, masks = [None] * 4, [0] * 4, {0}
    counts = (1323, 1, 1, 1)
    crt, prefix_paths = None, []
    at, fragments = 0, 0
    while at < len(payload):
        require(fragments < 1336, "link dump fragment budget")
        fragments += 1
        if payload.startswith(b"ar rcs ", at):
            matches = []
            for role, basename in enumerate(ARCHIVES):
                if archives[role] is None:
                    match = _path(payload, at + 7, basename)
                    if match is not None:
                        matches.append((role, match))
            require(len(matches) == 1, "link dump archive header identity or multiplicity")
            role, (path, at) = matches[0]
            archives[role] = path
            prefix_paths.append(path.decode("ascii"))
            continue
        if payload[at] == 32:
            matches = []
            for role in range(4):
                if archives[role] is not None and indexes[role] < counts[role]:
                    basename = MUSL_OBJECTS[indexes[0]] if role == 0 else ZCU[role]
                    match = _path(payload, at + 1, basename)
                    if match is not None:
                        matches.append((role, match))
            require(len(matches) == 1, "link dump ordered object fragment")
            role, (path, at) = matches[0]
            require(role == 0 or path.rsplit(b"/", 1)[0] == archives[role].rsplit(b"/", 1)[0],
                    "link dump ZCU archive binding")
            indexes[role] += 1
            prefix_paths.append(path.decode("ascii"))
            continue
        if payload[at] == 10:
            eligible = sum(1 << role for role in range(4)
                           if archives[role] is not None and indexes[role] == counts[role])
            advanced = {mask | (1 << role) for mask in masks for role in range(4)
                        if eligible & (1 << role) and not mask & (1 << role)}
            require(advanced and len(advanced) <= 16, "link dump archive newline obligations")
            masks = advanced
            at += 1
            continue
        if payload.startswith(CRT_PREFIX, at):
            require(crt is None, "link dump repeated CRT producer")
            out = _path(payload, at + len(CRT_PREFIX), b"crt1.o")
            require(out is not None, "link dump CRT output")
            require(payload[out[1]:out[1] + 1] == b" ", "link dump CRT spacing")
            inner = _path(payload, out[1] + 1, b"crt1.o")
            require(inner is not None and payload[inner[1]:inner[1] + 1] == b"\n", "link dump CRT input/framing")
            require(out[0] != inner[0], "link dump CRT inner/output alias")
            crt = out[0]
            prefix_paths.extend((out[0].decode("ascii"), inner[0].decode("ascii")))
            at = inner[1] + 1
            continue
        if payload.startswith(FINAL_PREFIX, at):
            require(crt is not None and all(archives) and tuple(indexes) == counts and 15 in masks,
                    "link dump final before complete cold producers")
            raw_roles = (crt, archives[2], archives[0], archives[3], archives[1])
            expected = (FINAL_PREFIX + crt + b" /work/policy.o /work/policy-controls.o " + archives[2] +
                        b" --as-needed " + archives[0] + b" " + archives[3] + b" " + archives[1] + b"\n")
            require(len(expected) == 554 and payload[at:] == expected, "link dump exact final vector and EOF")
            require(len(payload) == 80367 and fragments == 1336 and len(prefix_paths) == 1332,
                    "link dump complete cold byte/fragment/path accounting")
            words = expected[:-1].decode("ascii").split(" ")
            require(len(words) == 26 <= 96 and all(0 < len(word) <= 1024 for word in words) and
                    len(expected) <= 8192, "link dump final record/token budget")
            relative = tuple(path.decode("ascii") for path in raw_roles)
            require(len(set(relative)) == 5, "link dump runtime cardinality")
            return dict(words=words, rawRuntimePaths=relative,
                        runtimePaths=tuple("/work/" + path for path in relative),
                        prefixPaths=tuple(prefix_paths), runtimePositions=(18, 21, 23, 24, 25),
                        outputPosition=17, objectPosition=19, stackBytes=16777216,
                        imageBase=16777216, fragments=fragments, diagnosticBytes=len(payload))
        raise ValueError("link dump unrecognized fragment boundary")
    raise ValueError("link dump complete final vector absent")


def _observed(path, cache_rows):
    require(path in cache_rows, "link referenced input not observed")
    row = cache_rows[path]
    require(type(row) is dict and len(row) == 3 and all(type(key) is str for key in row) and
            set(row) == {"path", "bytes", "sha256"} and
            type(row["path"]) is str and row["path"] == path and
            type(row["bytes"]) is int and 0 < row["bytes"] <= 33554432 and
            type(row["sha256"]) is str and re.fullmatch(r"[0-9a-f]{64}", row["sha256"]),
            "link referenced observed identity")
    return row


def final_plan(model, payload, cache_rows):
    """Bind only after complete C.decode; return one fixed replay as data."""
    require(type(model) is str and model in MODELS, "link fixed model identity")
    value = decode(payload)
    require(type(cache_rows) is dict and len(cache_rows) <= 8192 and
            all(type(key) is str for key in cache_rows), "link bounded decoded cache rows")
    for raw in value["prefixPaths"]:
        _observed("/work/" + raw, cache_rows)
    inputs = [dict(_observed(path, cache_rows)) for path in value["runtimePaths"]]
    require(sum(row["bytes"] for row in inputs) <= 268435456, "link runtime aggregate bytes")
    argv = value["words"][1:]
    for position, path in zip(value["runtimePositions"], value["runtimePaths"]):
        argv[position - 1] = path
    argv[value["outputPosition"] - 1] = "/work/" + model + "-model"
    at = value["objectPosition"] - 1
    argv[at:at + 2] = ["/work/" + unit + ".o" for unit in MODELS[model]]
    extra = ["--emit-relocs", "--icf=none", "--no-relax", "--no-pie", "--Map=/work/" + model + ".map"]
    if model == "installer":
        extra += ["--wrap=" + name for name in WRAPS]
    return dict(model=model, argv=["/tool/zig", "ld.lld"] + extra + argv, runtimeInputs=inputs,
                rawRuntimePaths=value["rawRuntimePaths"], runtimePositions=value["runtimePositions"],
                preparationOutputRetainedAsModel=False, exactPerProcessProductionProved=False,
                nativeQualification=False)


def verify_unchanged(payload, earlier_rows, later_rows):
    """Compare all five exact runtime identities through full-map admission."""
    earlier = final_plan("policy", payload, earlier_rows)["runtimeInputs"]
    later = final_plan("policy", payload, later_rows)["runtimeInputs"]
    require(earlier == later, "link runtime observed identity changed")
    return earlier
